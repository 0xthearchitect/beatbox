#!/usr/bin/env python3
"""Re-vendor the fonts the BeatBox interface uses.

BeatBox runs labs with no route off the machine, so nothing it renders may
depend on reaching fonts.gstatic.com. The woff2 files are committed next to
the source.

Latin and Latin Extended only -- English and Portuguese are the two languages
this product speaks. Sora and IBM Plex are both SIL OFL 1.1.

Run it after changing a weight in ``web/src/tokens/index.ts``:

    python scripts/beatbox_fonts.py
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

WEB = Path(__file__).resolve().parents[1] / "beatbox" / "web"
FONT_DIR = WEB / "src" / "assets" / "fonts"
CSS_OUT = WEB / "src" / "styles" / "fonts.css"
SUBSETS = {"latin", "latin-ext"}
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/130.0 Safari/537.36")
SOURCE = ("https://fonts.googleapis.com/css2"
          "?family=Sora:wght@600;700"
          "&family=IBM+Plex+Sans:wght@400;500;600"
          "&family=IBM+Plex+Mono:wght@400;500"
          "&display=swap")

HEADER = """/* Bundled, not fetched. BeatBox runs labs that have no route off this machine;
   a UI that needed fonts.gstatic.com to render properly would be a strange
   thing to put in front of them.

   Latin and Latin Extended only -- Portuguese and English are the two
   languages this product speaks. Sora and IBM Plex are both SIL OFL 1.1.

   Generated by scripts/beatbox_fonts.py. Do not edit by hand. */

"""


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def main() -> int:
    css = fetch(SOURCE).decode("utf-8")
    blocks = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*@font-face\s*\{(.*?)\}", css, re.S)
    if not blocks:
        print("Google Fonts returned no @font-face blocks", file=sys.stderr)
        return 1

    FONT_DIR.mkdir(parents=True, exist_ok=True)
    for stale in FONT_DIR.glob("*.woff2"):
        stale.unlink()

    faces: list[str] = []
    written = 0
    for subset, body in blocks:
        if subset not in SUBSETS:
            continue
        family = re.search(r"font-family:\s*'([^']+)'", body).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", body).group(1)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", body).group(1)
        unicode_range = re.search(r"unicode-range:\s*([^;]+);", body).group(1).strip()
        slug = f"{family.lower().replace(' ', '-')}-{weight}-{subset}.woff2"
        (FONT_DIR / slug).write_bytes(fetch(url))
        written += 1
        faces.append(
            f"/* {family} {weight} — {subset} */\n"
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('../assets/fonts/{slug}') format('woff2');\n"
            f"  unicode-range: {unicode_range};\n"
            "}\n"
        )

    CSS_OUT.write_text(HEADER + "\n".join(faces), encoding="utf-8")
    total = sum(path.stat().st_size for path in FONT_DIR.glob("*.woff2"))
    print(f"{written} files, {total / 1024:.0f} KB -> {FONT_DIR}")
    print(f"wrote {CSS_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
