import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseAst } from 'rolldown/parseAst';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const LANGUAGES = ['en', 'pt_PT'];
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const read = (path) => readFileSync(path, 'utf8');
const sorted = (values) => [...values].sort();

export function domainForKey(key, domains) {
  const [, prefix, screen] = key.split('.');
  const owner = prefix === 'screen' ? screen : prefix;
  const matches = Object.entries(domains).filter(([domain, prefixes]) => domain === owner || prefixes.includes(owner));
  if (matches.length !== 1) throw new Error(`Expected exactly one domain for ${key}`);
  return matches[0][0];
}

/** One-time, lossless migration. Refuse to overwrite an existing domain tree. */
export function migrate(root = ROOT) {
  const domains = JSON.parse(read(join(root, 'locales/domains.json')));
  const catalogues = Object.fromEntries(LANGUAGES.map((language) => {
    if (existsSync(join(root, 'locales', language))) throw new Error(`Domain tree already exists: ${language}`);
    return [language, parseCatalogue(read(join(root, 'locales', `${language}.json`)), language)];
  }));
  const problems = parityProblems(catalogues);
  if (problems.length) throw new Error(problems.join('\n'));
  const output = LANGUAGES.map((language) => {
    const buckets = {};
    for (const [key, value] of Object.entries(catalogues[language])) {
      const domain = domainForKey(key, domains);
      (buckets[domain] ??= {})[key] = value;
    }
    return [language, buckets];
  });
  for (const [language, buckets] of output) {
    const folder = join(root, 'locales', language);
    mkdirSync(folder);
    for (const [domain, strings] of Object.entries(buckets)) writeFileSync(join(folder, `${domain}.json`), json(strings));
  }
}

/** JSON.parse silently discards duplicate keys; inspect properties first. */
export function parseCatalogue(source, where) {
  const value = JSON.parse(source);
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`${where}: expected an object`);
  const ast = parseAst(`(${source})`);
  const seen = new Set();
  for (const property of ast.body[0].expression.properties) {
    const key = property.key.value;
    if (seen.has(key)) throw new Error(`${where}: duplicate key ${key}`);
    seen.add(key);
    if (!key.startsWith('beatbox.') || typeof value[key] !== 'string') {
      throw new Error(`${where}: ${key} must be a beatbox key with a string value`);
    }
  }
  return value;
}

export function loadCatalogues(root = ROOT) {
  const domains = JSON.parse(read(join(root, 'locales/domains.json')));
  return Object.fromEntries(LANGUAGES.map((language) => {
    const folder = join(root, 'locales', language);
    const strings = {};
    for (const file of readdirSync(folder).filter((name) => name.endsWith('.json')).sort()) {
      const path = join(folder, file);
      for (const [key, value] of Object.entries(parseCatalogue(read(path), path))) {
        if (Object.hasOwn(strings, key)) throw new Error(`${path}: duplicate key across domains: ${key}`);
        if (domainForKey(key, domains) !== file.slice(0, -5)) throw new Error(`${path}: wrong domain for ${key}`);
        strings[key] = value;
      }
    }
    return [language, Object.fromEntries(sorted(Object.keys(strings)).map((key) => [key, strings[key]]))];
  }));
}

export const placeholders = (sentence) => sorted(new Set([...sentence.matchAll(/\{(\w+)\}/g)].map((match) => match[1])));

export function parityProblems(catalogues) {
  const problems = [];
  const english = catalogues.en;
  for (const language of LANGUAGES.filter((name) => name !== 'en')) {
    const translated = catalogues[language];
    for (const key of Object.keys(english)) {
      if (!Object.hasOwn(translated, key)) problems.push(`${language}: missing ${key}`);
      else if (JSON.stringify(placeholders(english[key])) !== JSON.stringify(placeholders(translated[key]))) {
        problems.push(`${language}: placeholders differ for ${key}: en=${placeholders(english[key])}, ${language}=${placeholders(translated[key])}`);
      }
    }
    for (const key of Object.keys(translated)) if (!Object.hasOwn(english, key)) problems.push(`${language}: extra ${key}`);
  }
  return problems;
}

export function keyTypes(english) {
  return '// Generated by web/scripts/locales.mjs. Do not edit.\nexport type Key =\n'
    + sorted(Object.keys(english)).map((key) => `  | ${JSON.stringify(key)}`).join('\n')
    + ';\n\nexport type KeySuffix<P extends string> = Key extends infer K\n'
    + '  ? K extends `${P}${infer S}` ? S : never\n  : never;\n';
}

function files(folder, extension) {
  return readdirSync(folder, { withFileTypes: true }).flatMap((entry) => {
    const path = join(folder, entry.name);
    return entry.isDirectory() ? files(path, extension) : extension.test(entry.name) ? [path] : [];
  });
}

function visit(node, callback) {
  if (!node || typeof node !== 'object') return;
  if (typeof node.type === 'string') callback(node);
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach((child) => visit(child, callback));
    else if (value && typeof value === 'object') visit(value, callback);
  }
}

const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Which keys are used. A computed family (`beatbox.x.${id}`) keeps all its
 * members. The generic reason lookup is skipped, or every key would look used.
 * Helper-built Rust reason families live in usage-exceptions.json.
 */
export function usage(english, root = ROOT) {
  const keys = Object.keys(english);
  const used = new Set();
  const problems = [];
  for (const path of files(join(root, 'web/src'), /\.(ts|tsx)$/)) {
    if (path.endsWith('.d.ts') || path.endsWith('.typecheck.ts')) continue;
    const ast = parseAst(read(path), { lang: path.endsWith('.tsx') ? 'tsx' : 'ts' }, path);
    visit(ast, (node) => {
      if (node.type === 'Literal' && typeof node.value === 'string' && node.value.startsWith('beatbox.')) {
        if (Object.hasOwn(english, node.value)) used.add(node.value);
        else if (node.value.endsWith('.')) keys.filter((key) => key.startsWith(node.value)).forEach((key) => used.add(key));
      }
      if (!path.endsWith('i18n/index.ts') && node.type === 'TemplateLiteral' && node.quasis[0].value.cooked?.startsWith('beatbox.')) {
        const pattern = new RegExp(`^${node.quasis.map((part) => escape(part.value.cooked)).join('.*')}$`);
        const matched = keys.filter((key) => pattern.test(key));
        matched.forEach((key) => used.add(key));
        if (!matched.length) problems.push(`${relative(root, path)}: computed key family matches no catalogue key`);
      }
      if (node.type === 'CallExpression' && ['t', 'entryText', 'runtimeText'].includes(node.callee.name)) {
        const argument = node.arguments[0];
        if (argument?.type === 'Literal' && typeof argument.value === 'string' && !Object.hasOwn(english, argument.value)) {
          problems.push(`${relative(root, path)}: unknown key ${argument.value}`);
        }
      }
    });
  }
  // Covers shell lookups as well as reason! literals; helper-built names are
  // verified against the live engine by crates/api/tests/strings.rs.
  for (const folder of ['crates', 'shell/src']) {
    for (const path of files(join(root, folder), /\.(rs|py)$/)) {
      for (const match of read(path).matchAll(/['"]([a-z0-9_.-]+)['"]/g)) {
        for (const key of [match[1], `beatbox.${match[1]}`, `beatbox.api.${match[1]}`]) if (Object.hasOwn(english, key)) used.add(key);
      }
    }
  }
  return { unused: sorted(keys.filter((key) => !used.has(key))), problems };
}

export function run(args = process.argv.slice(2), root = ROOT) {
  if (args.includes('--migrate')) { migrate(root); return; }
  const catalogues = loadCatalogues(root);
  const problems = parityProblems(catalogues);
  const inventory = usage(catalogues.en, root);
  problems.push(...inventory.problems);
  const exceptions = JSON.parse(read(join(root, 'locales/usage-exceptions.json')));
  for (const key of inventory.unused) if (!Object.hasOwn(exceptions, key)) problems.push(`unused: ${key}`);
  for (const [key, reason] of Object.entries(exceptions)) {
    if (!Object.hasOwn(catalogues.en, key)) problems.push(`obsolete usage exception: ${key}`);
    else if (!inventory.unused.includes(key)) problems.push(`usage exception is now used; remove it: ${key}`);
    if (typeof reason !== 'string' || !reason.trim()) problems.push(`usage exception needs a reason: ${key}`);
  }
  if (args.includes('--report')) {
    console.log('No statically identified usage (computed families are counted conservatively):');
    inventory.unused.forEach((key) => console.log(`${key}${exceptions[key] ? ` — ${exceptions[key]}` : ''}`));
    const identical = Object.keys(catalogues.en).filter((key) => catalogues.en[key] === catalogues.pt_PT[key]);
    console.log(`Identical values (review candidates, proper names may be intentional): ${identical.length}`);
  }
  if (problems.length) throw new Error(problems.join('\n'));
  const artifacts = LANGUAGES.map((language) => [join(root, 'locales', `${language}.json`), json(catalogues[language])]);
  artifacts.push([join(root, 'web/src/i18n/keys.d.ts'), keyTypes(catalogues.en)]);
  for (const [path, content] of artifacts) {
    if (args.includes('--write')) writeFileSync(path, content);
    else if (read(path) !== content) problems.push(`stale generated file: ${relative(root, path)} (run npm --prefix web run locales:generate)`);
  }
  if (problems.length) throw new Error(problems.join('\n'));
  console.log(`Locales OK: ${Object.keys(catalogues.en).length} keys in ${LANGUAGES.length} languages; ${inventory.unused.length} documented usage exceptions.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try { run(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
